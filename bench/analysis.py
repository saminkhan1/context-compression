"""Free analyses over saved results (no model calls): error taxonomy, breakdowns by question type,
table size and width, and reading-cost scaling on DataBench.

Usage: python analysis.py <databench_dir>   -> prints Markdown (saved as results2/ANALYSIS.md)
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).parent
R = HERE / "results2"
TOON_SETS = [f"{r}-{s}" for r in ("large", "small") for s in (9001, 9002, 9003)]
NUM = re.compile(r"^-?\d+(\.\d+)?$")


def load(set_name: str, arm: str) -> list[dict]:
    f = R / set_name / f"{arm}.graded.jsonl"
    return [json.loads(line) for line in open(f)] if f.exists() else []


def tokens(r: dict) -> int:
    return sum(c["input"] + c["cache_write"] + c["cache_read"] + c["output"] for c in r.get("calls", []))


def failure_kind(r: dict) -> str:
    a = (r.get("actual") or "").strip()
    e = str(r.get("expected")).strip()
    if r.get("error"):
        return "infrastructure error"
    if r.get("hit_limit"):
        return "ran out of turns"
    if r.get("exec_error") or a.startswith(("ERROR", "EXEC_")):
        return "script crashed"
    if not a:
        return "no answer"
    if "\n" in a or len(a) > max(120, 4 * len(e)):
        return "verbose / reasoning instead of answer"
    an, en = a.replace(",", ""), e.replace(",", "")
    if NUM.match(an) and NUM.match(en):
        x, y = float(an), float(en)
        rel = abs(x - y) / max(abs(y), 1e-9)
        if rel < 0.01:
            return "rounding / precision"
        return "near miss (<20%)" if rel < 0.2 else "wrong number"
    split = lambda s: {t.strip(" '\"[]").lower() for t in re.split(r"[,\n]", s) if t.strip(" '\"[]")}
    if "," in e or e.startswith("["):
        sa, se = split(a), split(e)
        if sa == se:
            return "list order / format"
        if sa & se:
            return "partial list"
    if a.lower().strip(" .'\"") == e.lower().strip(" .'\""):
        return "case / punctuation"
    return "wrong value"


def pct(k: int, n: int) -> str:
    return f"{100 * k / n:.1f}%" if n else "–"


def table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def taxonomy(title: str, groups: dict[str, list[dict]]) -> str:
    kinds = Counter()
    per = {}
    for arm, rs in groups.items():
        c = Counter(failure_kind(r) for r in rs if not r["isCorrect"])
        per[arm] = (c, len(rs))
        kinds.update(c)
    order = [k for k, _ in kinds.most_common()]
    rows = [[arm, f"{sum(c.values())} of {n}"] + [c.get(k, 0) for k in order] for arm, (c, n) in per.items()]
    return f"### {title}\n\n" + table(["arm", "wrong"] + order, rows)


def main() -> None:
    db = Path(sys.argv[1])
    sizes = {n: (rows, cols) for n, rows, cols, _ in json.load(open(db / "tables.json"))}
    split = json.load(open(db / "split.json"))
    out = ["# Free analyses (no model calls)", "",
           "Generated by `bench/analysis.py` from the saved per-question results. claude-haiku-4-5 only.", ""]

    # ---- error taxonomy
    out.append("## 1. What goes wrong: failure taxonomy\n")
    out.append("Heuristic classification of every wrong answer (see `failure_kind` in `analysis.py`).\n")
    toon_arms = ["agent", "agent-nopreview", "code", "code-namesonly"]
    out.append(taxonomy("TOON benchmark, six fresh sets (n = 1,434 per arm)",
                        {a: [r for s in TOON_SETS for r in load(s, a)] for a in toon_arms}))
    out.append("")
    out.append(taxonomy("Reading in context, small seed 9001 (n = 239 per arm)",
                        {a: load("small-9001", a) for a in ("toon", "toon-think", "json-pretty", "json-compact")}))
    out.append("")
    out.append(taxonomy("Reading in context, large seed 9001 (n = 239)", {"toon": load("large-9001", "toon")}))
    out.append("")
    out.append(taxonomy("DataBench test (n = 1,613 per arm; table: 166)",
                        {a: load("databench-test", a) for a in ("agent", "agent-nopreview", "code", "table")}))
    out.append("")

    # ---- by question type (TOON)
    out.append("## 2. TOON benchmark by question type (six fresh sets)\n")
    arms = ["agent", "agent-nopreview", "code"]
    data = {a: [r for s in TOON_SETS for r in load(s, a)] for a in arms}
    small_read = {a: load("small-9001", a) for a in ("toon", "toon-think", "json-pretty")}
    types = sorted({r["type"] for r in data["agent"]})
    rows = []
    for t in types:
        row = [t, sum(1 for r in data["agent"] if r["type"] == t)]
        for a in arms:
            rs = [r for r in data[a] if r["type"] == t]
            row.append(pct(sum(r["isCorrect"] for r in rs), len(rs)))
        for a, rs0 in small_read.items():
            rs = [r for r in rs0 if r["type"] == t]
            row.append(pct(sum(r["isCorrect"] for r in rs), len(rs)))
        rows.append(row)
    out.append(table(["question type", "n (per agent arm)"] + arms + ["toon (small 9001)", "toon-think (small 9001)",
                                                                       "json-pretty (small 9001)"], rows))
    out.append("\nReading fails on aggregation and filtering (counting rows in context); with thinking on it recovers "
               "most of them. Field lookups are near-perfect for every method.\n")

    # ---- DataBench breakdowns
    out.append("## 3. DataBench test by answer type, table size and width\n")
    dbarms = ["agent", "agent-nopreview", "code"]
    D = {a: load("databench-test", a) for a in dbarms}
    def breakdown(label: str, key, buckets: list[str]) -> str:
        rows = []
        for b in buckets:
            row = [b]
            n = None
            for a in dbarms:
                rs = [r for r in D[a] if key(r) == b]
                n = len(rs)
                row.append(f"{pct(sum(r['isCorrect'] for r in rs), n)} / {sum(map(tokens, rs)) / max(n, 1):,.0f}")
            rows.append([row[0], n] + row[1:])
        return f"### By {label} (accuracy / tokens per question)\n\n" + table([label, "n"] + dbarms, rows)

    out.append(breakdown("answer type", lambda r: r["type"],
                         ["boolean", "number", "category", "list[number]", "list[category]"]))
    out.append("")
    def size_bucket(r):
        rows_ = sizes[r["dataset"]][0]
        return "< 1k rows" if rows_ < 1000 else "1k–10k" if rows_ < 10000 else "10k–100k" if rows_ < 100000 else "≥ 100k"
    out.append(breakdown("table rows", size_bucket, ["< 1k rows", "1k–10k", "10k–100k", "≥ 100k"]))
    out.append("")
    def width_bucket(r):
        c = sizes[r["dataset"]][1]
        return "< 10 columns" if c < 10 else "10–24" if c < 25 else "≥ 25"
    out.append(breakdown("table width", width_bucket, ["< 10 columns", "10–24", "≥ 25"]))
    out.append("")

    # ---- reading cost scaling (offline)
    out.append("## 4. Reading cost versus querying cost on DataBench (offline token counts)\n")
    test = split["test"]
    toks = split["csv_tokens"]
    by = defaultdict(list)
    for n in test:
        by["< 10k" if toks[n] < 1e4 else "10k–200k" if toks[n] < 2e5 else "200k–1M" if toks[n] < 1e6 else "≥ 1M"].append(n)
    rows = []
    for b in ["< 10k", "10k–200k", "200k–1M", "≥ 1M"]:
        names = by[b]
        qs = [r for r in D["agent"] if r["dataset"] in names]
        rows.append([b, len(names), len(qs),
                     f"{sum(toks[n] for n in names) / max(len(names), 1):,.0f}",
                     f"{sum(map(tokens, qs)) / max(len(qs), 1):,.0f}",
                     "yes" if b in ("< 10k", "10k–200k") else "no"])
    out.append(table(["CSV size of table (o200k tokens)", "tables", "questions", "mean CSV tokens (reading cost)",
                      "agent tokens per question (measured)", "fits a 200k context window"], rows))
    over = sum(1 for n in test if toks[n] >= 2e5)
    qover = sum(1 for r in D["agent"] if toks[r["dataset"]] >= 2e5)
    out.append(f"\n{over} of {len(test)} DataBench test tables ({qover} of {len(D['agent'])} questions) are too large to "
               "read into a 200k-token context at all. Across these size bands the reading cost grows by about "
               "2,500x while the agent's measured cost grows from about 5.7k to 8.8k tokens per question.\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
